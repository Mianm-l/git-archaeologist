"""
Markdown Exporter for Git-Archaeologist.
Produces clean, GitHub-Flavored Markdown reports ideal for PR discussions and issues.
"""

from __future__ import annotations
from git_archaeologist.core.excavator import ExcavationReport


def generate_markdown_report(report: ExcavationReport) -> str:
    target = report.target
    risk = report.risk
    gen = report.genesis_node.commit_meta
    ctx = report.context

    badge_emoji = "🔴" if risk.level in ("CRITICAL_LOAD_BEARING", "HIGH") else ("🟡" if risk.level == "MODERATE" else "🟢")

    md = [
        f"## 🏛️ Git-Archaeologist Dossier: `{target.rel_path}:{target.start_line}-{target.end_line}`",
        "",
        f"### {badge_emoji} Archaeological Risk Index: **{risk.total_score}/100** ({risk.level})",
        "",
        f"> **Verdict**: {risk.recommendation}",
        "",
        "### 📍 Target Code Snippet",
        "```",
        target.code_snippet.strip(),
        "```",
        "",
        "### 🌱 True Genesis Event (起源提交)",
        f"- **Commit**: `{gen.short_hash}` (`{gen.hash}`)",
        f"- **Author**: {gen.author_name} `<{gen.author_email}>`",
        f"- **Date**: {gen.date_str[:10]}",
        f"- **Intent**: `{ctx.intent}` (Confidence: {int(ctx.intent_confidence*100)}%)",
        f"- **Subject**: {gen.subject}",
    ]

    if ctx.linked_issues:
        md.append(f"- **Linked Issues / PRs**: {', '.join(f'`{i}`' for i in ctx.linked_issues)}")
    if ctx.cves:
        md.append(f"- **CVE Identifiers**: {', '.join(f'`{c}`' for c in ctx.cves)}")

    md.extend([
        "",
        "### 🛡️ Co-Committed Regression Tests",
    ])
    if ctx.co_changed_tests:
        for t in ctx.co_changed_tests:
            md.append(f"- 🧪 `{t}`")
    else:
        md.append("⚠️ *No test suites were co-committed in the genesis commit. Invariants may be implicit.*")

    md.extend([
        "",
        "### 📋 Recommended Protocol",
    ])
    for act in risk.action_items:
        md.append(f"- [ ] {act}")

    md.extend([
        "",
        f"### 📜 Evolution Timeline ({len(report.timeline)} events, {report.churn_commits_bypassed} churn bypassed)",
        "| Hash | Date | Role | Author | Subject |",
        "| :--- | :--- | :--- | :--- | :--- |"
    ])

    for node in report.timeline:
        m = node.commit_meta
        role_str = f"**{node.role}**" if node.role == "GENESIS" else node.role
        if node.is_noise:
            role_str = f"🧹 Churn ({node.noise_reason[:20]})"
        subj_clean = m.subject.replace("|", "/")
        md.append(f"| `{m.short_hash}` | {m.date_str[:10]} | {role_str} | {m.author_name} | {subj_clean} |")

    md.append("")
    md.append("---")
    md.append("*Generated by [Git-Archaeologist](https://github.com/Mianm-l/git-archaeologist)*")

    return "\n".join(md)
